def guard_environment():
    """Warn (never fail) when the recommended deterministic settings are missing."""
    sys.dont_write_bytecode = True
    missing = [k for k, v in RECOMMENDED_ENV.items() if os.environ.get(k) != v]
    if missing:
        warnings.warn(f"Recommended environment variables not set: {missing} (see RECOMMENDED_ENV in experiments/common.py)")


def load_module(name, path):
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def save_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(value, ensure_ascii=False, indent=1, allow_nan=False) + "\n")
    tmp.replace(path)


def read_json(path):
    return json.loads(Path(path).read_text())


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()
