"""Paths, small helpers and the single configuration mechanism of the experiment scripts.

All locations are set through environment variables, with defaults relative to the repository:

  SPI_WORK   work directory (default: <repo>/work). Holds everything the scripts read or write:
               hf_models/<name>/                    Hugging Face model directories
               db/<model_key>/                      level databases (see README, "Level databases")
               models/<model_key>/                  per-model protocol data:
                   fineweb/{search_tokens.pt, heldout_tokens.pt, documents.json}
                   flops_table.json                 active heads / KV groups / MLP dims per (layer, level)
                   teacher_search_8x2048_bf16.pt    dense-model logits on the 8 search windows
               runs/<run_name>/                     search runs (job.json, progress.json, results.json, eval_cache.jsonl)
               api/                                 optional: stored LLM responses and cost log
               benchmark/, reports/, recovery/, speed/, moe/   outputs of the later stages
  SPI_EVAL_CACHES   optional, os.pathsep-separated directories whose eval_cache.jsonl files may be reused
                    (same protocol only; conflicting values abort the run)
  OPENAI_API_KEY, DEEPSEEK_API_KEY   API keys, only needed when an LLM is called

Recommended environment for reproducible runs (not enforced; see RECOMMENDED_ENV): PYTHONHASHSEED=0 and
single-threaded BLAS/OpenMP.
"""
